"""
The real-race excerpt in tests/fixtures/race_excerpt/, opened for tests.

Eight laps of the 2025 Hungarian GP (session 9928), regenerated by
`python -m tests.fixtures.make_race_excerpt`. Loaded once per test session:
building its timeline is the slow part, and nothing a test does changes it.
"""
from datetime import datetime
from functools import lru_cache
from pathlib import Path

from app.replay.engine import RaceReplay
from app.replay.store import SessionStore

EXCERPT_ROOT = Path(__file__).resolve().parent / "fixtures" / "race_excerpt"
EXCERPT_SESSION = 9928


def excerpt_store() -> SessionStore:
    return SessionStore(EXCERPT_ROOT)


@lru_cache(maxsize=1)
def excerpt_replay() -> RaceReplay:
    return RaceReplay(excerpt_store().load(EXCERPT_SESSION))


def excerpt_with_safety_car(root: Path, deployed: datetime, ended: datetime) -> RaceReplay:
    """
    The excerpt with a safety car period written into race control, cached
    under `root`. The real eight laps have none.
    """
    archive = excerpt_store().load(EXCERPT_SESSION)
    rows = {endpoint: list(archive.rows(endpoint)) for endpoint in archive.manifest.endpoints}
    rows["race_control"] += [
        {"date": deployed.isoformat(), "category": "SafetyCar", "flag": None,
         "scope": "Track", "message": "SAFETY CAR DEPLOYED"},
        {"date": ended.isoformat(), "category": "Flag", "flag": "GREEN",
         "scope": "Track", "message": "TRACK CLEAR"},
    ]
    archive.manifest.endpoints = {}
    store = SessionStore(root)
    store.save(archive.manifest, rows)
    return RaceReplay(store.load(EXCERPT_SESSION))
